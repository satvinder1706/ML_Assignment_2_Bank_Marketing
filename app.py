from pathlib import Path
import io
import json
import joblib
import pandas as pd
import streamlit as st
from sklearn.metrics import (accuracy_score, roc_auc_score, precision_score,
                             recall_score, f1_score, matthews_corrcoef,
                             confusion_matrix, classification_report)


def read_labelled_csv(file_obj):
    """Read a standard CSV or repair rows wrapped in an extra pair of quotes."""
    raw = file_obj.getvalue() if hasattr(file_obj, "getvalue") else file_obj.read()
    text = raw.decode("utf-8-sig") if isinstance(raw, bytes) else raw

    data = pd.read_csv(io.StringIO(text))

    # Repair malformed files where each entire CSV row is quoted as one field.
    if len(data.columns) == 1 and "," in str(data.columns[0]):
        repaired_lines = []
        for line in text.splitlines():
            line = line.strip()
            if line.startswith('"') and line.endswith('"'):
                line = line[1:-1]
            repaired_lines.append(line)
        data = pd.read_csv(io.StringIO("\n".join(repaired_lines)))

    data.columns = data.columns.astype(str).str.strip()
    return data

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "knearest_neighbors.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}
st.set_page_config(page_title="Bank Marketing Classifier", page_icon="🏦", layout="wide")
st.title("🏦 Bank Marketing Subscription Predictor")
st.write("Compare five classification algorithms on the UCI Bank Marketing dataset.")
st.info("Upload the labelled test_data.csv generated by train.py. The target column must be named **y**.")

available = {name: path for name, filename in MODEL_FILES.items()
             if (path := MODEL_DIR / filename).exists()}
if not available:
    st.error("No trained model files found. Run `python train.py` first.")
    st.stop()

selected = st.selectbox("Select classification model", list(available.keys()))
uploaded = st.file_uploader("Upload labelled test data (CSV)", type=["csv"])
if uploaded is None:
    st.caption("The repository's test_data.csv can be used for the demonstration.")
    default_file = ROOT / "test_data.csv"
    if default_file.exists():
        with open(default_file, "rb") as f:
            data = read_labelled_csv(f)
    else:
        st.warning("Upload test_data.csv to continue.")
        st.stop()
else:
    data = read_labelled_csv(uploaded)

st.success(f"Test data loaded successfully: {data.shape[0]} rows and {data.shape[1]} columns.")
st.caption(f"Detected target column: y | Target values: {sorted(data['y'].astype(str).str.strip().str.lower().unique().tolist()) if 'y' in data.columns else 'not found'}")

if "y" not in data.columns:
    st.error(f"CSV must contain the actual target column `y`. Detected columns: {data.columns.tolist()}")
    st.stop()

actual_raw = data["y"].astype(str).str.strip().str.lower()
X = data.drop(columns=["y"])
with open(MODEL_DIR / "label_classes.json") as f:
    classes = json.load(f)
class_to_int = {str(label).lower(): i for i, label in enumerate(classes)}
if not set(actual_raw.unique()).issubset(set(class_to_int)):
    st.error(f"Target values must be from: {classes}")
    st.stop()
y_true = actual_raw.map(class_to_int).astype(int).to_numpy()

model = joblib.load(available[selected])
try:
    y_pred = model.predict(X)
    scores = model.predict_proba(X)[:, 1] if hasattr(model, "predict_proba") else model.decision_function(X)
except Exception as exc:
    st.error(f"Could not score this file. Ensure its columns match the UCI test data. Details: {exc}")
    st.stop()

metrics = {
    "Accuracy": accuracy_score(y_true, y_pred),
    "AUC": roc_auc_score(y_true, scores),
    "Precision": precision_score(y_true, y_pred, zero_division=0),
    "Recall": recall_score(y_true, y_pred, zero_division=0),
    "F1 Score": f1_score(y_true, y_pred, zero_division=0),
    "MCC": matthews_corrcoef(y_true, y_pred)
}
st.subheader(f"Evaluation: {selected}")
cols = st.columns(6)
for col, (label, value) in zip(cols, metrics.items()):
    col.metric(label, f"{value:.4f}")

left, right = st.columns(2)
with left:
    st.subheader("Confusion matrix")
    cm = confusion_matrix(y_true, y_pred)
    st.dataframe(pd.DataFrame(cm, index=[f"Actual {c}" for c in classes],
                              columns=[f"Predicted {c}" for c in classes]))
with right:
    st.subheader("Classification report")
    report = classification_report(y_true, y_pred, target_names=classes,
                                   output_dict=True, zero_division=0)
    st.dataframe(pd.DataFrame(report).transpose().round(4))

st.subheader("Predictions preview")
preview = X.head(20).copy()
preview["Actual"] = [classes[i] for i in y_true[:20]]
preview["Predicted"] = [classes[i] for i in y_pred[:20]]
st.dataframe(preview, use_container_width=True)
st.download_button("Download predictions", preview.to_csv(index=False),
                   file_name="bank_marketing_predictions.csv", mime="text/csv")
